/**
 * Finds a state/UT definition by its canonical name or alias (case-insensitive).
 */
export function findIndiaLocation(stateOrAlias: string | null | undefined): IndiaLocation | undefined {
  if (!stateOrAlias || typeof stateOrAlias !== "string") return undefined;
  const normalized = stateOrAlias.trim().toLowerCase();
  if (!normalized) return undefined;

  return INDIA_LOCATIONS.find((loc) => {
    if (loc.state.toLowerCase() === normalized) return true;
    if (loc.aliases && loc.aliases.some((a) => a.toLowerCase() === normalized)) return true;
    return false;
  });
}

/**
 * Returns all 36 canonical Indian State and UT names sorted alphabetically.
 */
export function getAllIndianStateNames(): string[] {
  return INDIA_LOCATIONS.map((loc) => loc.state).sort((a, b) => a.localeCompare(b));
}

/**
 * Returns all curated cities for a given state name or alias.
 */
export function getCitiesForIndianState(stateName: string): string[] {
  const loc = findIndiaLocation(stateName);
  if (!loc) return [];
  return [...loc.cities].sort((a, b) => a.localeCompare(b));
}

/**
 * Checks if a city belongs to the curated list of a given state (case-insensitive).
 */
export function isCityInIndianState(stateName: string, cityName: string): boolean {
  if (!cityName) return false;
  const cities = getCitiesForIndianState(stateName);
  const normalizedCity = cityName.trim().toLowerCase();
  return cities.some((c) => c.toLowerCase() === normalizedCity);
}

/**
 * Canonicalizes a state name string if found in master; otherwise returns the original trimmed string.
 */
export function canonicalizeStateName(stateName: string): string {
  const loc = findIndiaLocation(stateName);
  return loc ? loc.state : stateName.trim();
}
